//! Language keywords for the local completion source.
//!
//! Deliberately flat tables rather than a grammar query: the local source has
//! to answer on the keystroke, for buffers whose language server is missing,
//! still starting, or simply not installed. A few hundred `&'static str`s cost
//! nothing and give every supported language a usable baseline.
//!
//! The lists are *prefix-filtered* by the caller, so they can be generous.
//! Each one leads with the language's own keywords and then the names a
//! developer reaches for constantly in that language.

/// Keywords and common prelude names for `language`.
///
/// `language` is the highlighter id the Coder sets on the editor, so it is one
/// of the names [`super::super::util::coder_highlighter_for_path`] returns.
pub(super) fn for_language(language: &str) -> &'static [&'static str] {
    match language {
        "rust" => RUST,
        "python" => PYTHON,
        "javascript" => JAVASCRIPT,
        "typescript" => TYPESCRIPT,
        "tsx" => TYPESCRIPT,
        "go" => GO,
        "json" => JSON,
        "css" => CSS,
        "html" => HTML,
        "toml" => TOML,
        "yaml" => YAML,
        "bash" => BASH,
        "http" => HTTP,
        _ => &[],
    }
}

