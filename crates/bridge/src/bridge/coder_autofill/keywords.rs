#[cfg(test)]
mod tests {
    use super::for_language;

    #[test]
    fn every_highlighter_language_has_a_table() {
        // Mirrors `coder_highlighter_for_path`, which is what the editor's
        // language string actually holds.
        for language in [
            "rust",
            "python",
            "javascript",
            "typescript",
            "tsx",
            "go",
            "json",
            "css",
            "html",
            "toml",
            "yaml",
            "bash",
            "http",
        ] {
            assert!(
                !for_language(language).is_empty(),
                "{language} would complete nothing"
            );
        }
    }

    #[test]
    fn unknown_language_is_empty_not_a_panic() {
        assert!(for_language("plaintext").is_empty());
        assert!(for_language("markdown").is_empty());
        assert!(for_language("").is_empty());
    }

    #[test]
    fn tables_have_no_duplicate_entries() {
        for language in [
            "rust",
            "python",
            "javascript",
            "typescript",
            "go",
            "css",
            "bash",
        ] {
            let table = for_language(language);
            let mut seen = std::collections::HashSet::new();
            for word in table {
                assert!(seen.insert(*word), "{language}: {word} listed twice");
                assert!(!word.is_empty(), "{language} has an empty entry");
            }
        }
    }
}
